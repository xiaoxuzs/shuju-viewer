// Generates front/src/features/bu/generated/unimodLabels.generated.ts from a
// local UniMod XML snapshot. Offline-only: never fetches the network.
//
// Usage: node scripts/generate-unimod-labels.mjs
// Update the snapshot manually at third_party/unimod/unimod.xml, then re-run.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE_URL = "https://www.unimod.org/xml/unimod.xml";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(scriptDir, "..");
const xmlPath = resolve(repoRoot, "third_party/unimod/unimod.xml");
const outPath = resolve(
  repoRoot,
  "front/src/features/bu/generated/unimodLabels.generated.ts",
);

function decodeXmlEntities(value) {
  return value
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&amp;/g, "&");
}

function parseAttributes(attrText) {
  const attrs = {};
  const attrRegex = /([\w:-]+)="([^"]*)"/g;
  let match;
  while ((match = attrRegex.exec(attrText)) !== null) {
    attrs[match[1]] = decodeXmlEntities(match[2]);
  }
  return attrs;
}

function parseUnimodXml(xml) {
  // Matches <mod ...> and namespaced variants like <umod:mod ...>.
  const modTagRegex = /<[^:>\s]*:?mod\b([^>]*)>/g;
  const labels = {};
  let match;
  while ((match = modTagRegex.exec(xml)) !== null) {
    const attrs = parseAttributes(match[1]);
    const id = attrs.record_id;
    if (!id) continue;
    const label = attrs.title || attrs.full_name;
    if (!label) continue;
    labels[id] = label;
  }
  return labels;
}

function buildFileContents(labels) {
  const sortedKeys = Object.keys(labels).sort((a, b) => Number(a) - Number(b));
  const body = sortedKeys
    .map((key) => `  ${JSON.stringify(key)}: ${JSON.stringify(labels[key])},`)
    .join("\n");
  return `// AUTO-GENERATED by scripts/generate-unimod-labels.mjs. Do not edit by hand.
// Source: ${SOURCE_URL} (local snapshot at third_party/unimod/unimod.xml)
// Maps UniMod accession (record_id) -> display label (title || full_name).

export const UNIMOD_LABELS: Record<string, string> = {
${body}
};

export const UNIMOD_LABEL_SOURCE = {
  source: ${JSON.stringify(SOURCE_URL)},
  generatedAt: ${JSON.stringify(new Date().toISOString())},
};
`;
}

function main() {
  if (!existsSync(xmlPath)) {
    console.error(
      `[generate-unimod-labels] Snapshot not found: ${xmlPath}\n` +
        `Download ${SOURCE_URL} manually and place it there, then re-run.`,
    );
    process.exit(1);
  }

  const xml = readFileSync(xmlPath, "utf8");
  const labels = parseUnimodXml(xml);
  const count = Object.keys(labels).length;

  if (count === 0) {
    console.error(
      "[generate-unimod-labels] Parsed 0 modifications. Is the XML snapshot valid?",
    );
    process.exit(1);
  }

  // Minimal self-check against well-known UniMod accessions.
  const expected = { 4: "Carbamidomethyl", 21: "Phospho", 35: "Oxidation" };
  const failures = Object.entries(expected).filter(
    ([id, label]) => labels[id] !== label,
  );
  if (failures.length > 0) {
    console.warn(
      "[generate-unimod-labels] Self-check mismatch (continuing): " +
        failures
          .map(([id, label]) => `UniMod:${id} expected "${label}" got "${labels[id] ?? "<missing>"}"`)
          .join("; "),
    );
  }

  writeFileSync(outPath, buildFileContents(labels), "utf8");
  console.log(
    `[generate-unimod-labels] Wrote ${count} labels to ${outPath}`,
  );
}

main();
